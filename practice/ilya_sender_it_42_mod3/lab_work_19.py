import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from scipy.optimize import linprog


# Класифікація математичних моделей та перевірка адекватності
# Варіант 9 — Суми

np.random.seed(9)

city = "Суми"
base_temp = 7.5
amplitude = 14
base_consumption = 950
k = 24
noise_sd = 28

months = np.arange(1, 13)

temp = base_temp + amplitude * np.cos(
    (months - 7) / 12 * 2 * np.pi
)

temp = np.round(
    temp + np.random.normal(0, 0.5, size=12), 1
)

consumption = (
    base_consumption
    - k * (temp - base_temp)
    + np.random.normal(0, noise_sd, size=12)
)

consumption = np.round(consumption, 0)

city_data = pd.DataFrame({
    "місяць": months,
    "температура": temp,
    "споживання_МВтгод": consumption,
})

print("=" * 65)
print("ПРАКТИЧНА РОБОТА № 19 — ВАРІАНТ 9")
print("Місто:", city)
print("=" * 65)

print("\nВихідний набір даних:")
print(city_data.to_string(index=False))


# Завдання 1. Класифікація математичної моделі

print("\nЗавдання 1. Класифікація моделі")

print(
    "1. За характером невизначеності модель стохастична: "
    "лінійна залежність доповнюється випадковою похибкою."
)

print(
    "2. За призначенням модель описова та прогнозна. "
    "Вона не є балансовою, оптимізаційною чи імітаційною."
)

print(
    "3. За залежністю від часу модель статична: "
    "споживання прогнозується за температурою того самого місяця, "
    "без використання попередніх значень споживання."
)


# Завдання 2. Побудова лінійної моделі

b, a = np.polyfit(
    city_data["температура"],
    city_data["споживання_МВтгод"],
    1
)

city_data["передбачення"] = (
    a + b * city_data["температура"]
)

print("\nЗавдання 2. Лінійна модель")

print(
    f"Споживання ≈ {a:.2f} "
    f"+ ({b:.2f}) * температура"
)

print("Коефіцієнт b =", round(b, 4))

if b < 0:
    print(
        "Коефіцієнт від'ємний: зі зростанням температури "
        "споживання електроенергії зменшується."
    )
else:
    print(
        "Коефіцієнт додатний: отриманий напрямок залежності "
        "не відповідає очікуваному ефекту опалення."
    )


# Завдання 3. Залишки, R² та оцінка адекватності

city_data["залишок"] = (
    city_data["споживання_МВтгод"]
    - city_data["передбачення"]
)

residuals = city_data["залишок"]

ss_res = (residuals ** 2).sum()

ss_tot = (
    (
        city_data["споживання_МВтгод"]
        - city_data["споживання_МВтгод"].mean()
    ) ** 2
).sum()

r_squared = 1 - ss_res / ss_tot

print("\nЗавдання 3. Порівняння спостережень і прогнозів")

print(
    city_data[
        [
            "місяць",
            "температура",
            "споживання_МВтгод",
            "передбачення",
            "залишок",
        ]
    ].round(2).to_string(index=False)
)

print("\nСума квадратів залишків =", round(ss_res, 2))
print("R² =", round(r_squared, 4))

print(
    "R² показує частку варіації споживання, "
    "пояснену лінійною моделлю в цьому наборі даних."
)


# Графік залишків проти місяця

plt.figure(figsize=(9, 5))

plt.scatter(
    city_data["місяць"],
    city_data["залишок"],
    label="Залишки"
)

plt.axhline(
    0,
    color="red",
    linestyle="--",
    label="Нульовий рівень"
)

plt.xticks(months)
plt.xlabel("Місяць")
plt.ylabel("Залишок, МВт·год")
plt.title("Практична № 19: залишки за місяцями")
plt.legend()
plt.grid(True)
plt.show()


# Графік залишків проти температури

plt.figure(figsize=(9, 5))

plt.scatter(
    city_data["температура"],
    city_data["залишок"]
)

plt.axhline(0, color="red", linestyle="--")

plt.xlabel("Температура, °C")
plt.ylabel("Залишок, МВт·год")
plt.title("Практична № 19: залишки проти температури")
plt.grid(True)
plt.show()


print("\nОцінка адекватності:")

if r_squared >= 0.9:
    print(
        "R² високе: модель пояснює значну частину варіації "
        "споживання в межах наявних даних." )
else:
    print(
        "R² відносно низьке: варто розглянути "
        "додаткові фактори або іншу форму залежності."
    )

print(
    "Остаточна оцінка адекватності потребує також аналізу "
    "графіків залишків. Високе R² саме по собі "
    "не доводить правильності моделі."
)


# Завдання 4. Верифікація та валідація

print("\nЗавдання 4. Верифікація та валідація")

i = 0

manual_prediction = (
    a + b * city_data.loc[i, "температура"]
)

code_prediction = city_data.loc[i, "передбачення"]

print("Перевірка першого місяця:")

print(
    "Ручний розрахунок =",
    round(manual_prediction, 2)
)

print(
    "Результат коду =",
    round(code_prediction, 2)
)

print(
    "Верифікація: перевіряємо правильність реалізації "
    "формули a + b * температура та відповідність "
    "обчислень ручному розрахунку."
)

print(
    "Валідація: перевіряємо, наскільки прогнози відповідають "
    "фактичному споживанню. Для незалежної перевірки "
    "потрібні нові дані, не використані під час підбору "
    "коефіцієнтів, наприклад дані наступного року."
)


